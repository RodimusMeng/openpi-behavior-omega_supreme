"""Fail-closed validation for a BEHAVIOR challenge result bundle.

This checker validates the *static* evidence shipped in a submission bundle:
the manifest, source/config hashes, evaluator output inventory, and the JSON
and MP4 files produced by the official evaluator.  It deliberately does not
claim that the files were generated by an untampered evaluator; a manifest
field such as ``outputs_unmodified`` is only meaningful when its recorded
artifact inventory still matches the bytes on disk.

The challenge documentation and the v3.9.1 scorer currently describe different
public result sets.  They are therefore explicit profiles instead of an
implicit, guessed convention:

``docs_public_report``
    Reported public results: CLI indices 0..9, resolving to instance IDs
    301..310.  ``--full-submission`` requires 100 tasks x 10 instances.

``score_utils_public``
    The official ``score_utils.compute_final_q_score`` public set: resolved
    instance IDs 301..320.  ``--full-submission`` requires 100 tasks x 20
    instances.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
import dataclasses
import hashlib
import json
from pathlib import Path
import re
from typing import Any

import numpy as np
import yaml

from openpi.weaver import behavior_compliance


@dataclasses.dataclass(frozen=True)
class BundleViolation:
    code: str
    detail: str


@dataclasses.dataclass(frozen=True)
class SubmissionProfile:
    name: str
    testset: str
    instance_ids: tuple[int, ...]
    cli_indices: tuple[int, ...] | None

    @property
    def instances_per_task(self) -> int:
        return len(self.instance_ids)


PROFILES = {
    "docs_public_report": SubmissionProfile(
        name="docs_public_report",
        testset="public",
        instance_ids=tuple(range(301, 311)),
        cli_indices=tuple(range(10)),
    ),
    "score_utils_public": SubmissionProfile(
        name="score_utils_public",
        testset="public",
        instance_ids=tuple(range(301, 321)),
        cli_indices=tuple(range(20)),
    ),
}

BEHAVIOR_V391_GIT_SHA = "26f2c7ef7b9cf96bd0414f81e1e751e493762779"
_BUNDLE_NAME = re.compile(r"^(standard|privileged)\.(public|hidden)\.([^\.]+)\.([^\.]+)\.([^\.]+)$")
_RESULT_NAME = re.compile(r"^(?P<task>.+)_(?P<instance>\d+)_(?P<rollout>\d+)\.json$")
_VIDEO_NAME = re.compile(r"^(?P<task>.+)_(?P<instance>\d+)_(?P<rollout>\d+)\.mp4$")
_SHA256 = re.compile(r"^[0-9a-fA-F]{64}$")


def validate_submission_bundle(
    root: str | Path,
    *,
    profile: str = "docs_public_report",
    full_submission: bool = False,
    manifest_name: str = "manifest.json",
) -> tuple[BundleViolation, ...]:
    """Return all violations found in a result bundle; never mutate ``root``."""

    violations: list[BundleViolation] = []
    bundle_root = Path(root).expanduser().resolve()
    selected = PROFILES.get(profile)
    if selected is None:
        return (BundleViolation("profile", f"unsupported profile {profile!r}"),)
    if not bundle_root.is_dir():
        return (BundleViolation("bundle_root", f"not a directory: {bundle_root}"),)

    match = _BUNDLE_NAME.fullmatch(bundle_root.name)
    bundle_track: str | None = None
    if match is None:
        violations.append(
            BundleViolation(
                "bundle_name",
                "bundle basename must be <track>.<testset>.<team>.<affiliation>.<date>",
            )
        )
    else:
        bundle_track, testset = match.group(1), match.group(2)
        if testset != selected.testset:
            violations.append(BundleViolation("bundle_testset", f"expected {selected.testset!r}, got {testset!r}"))

    manifest_path = _safe_relative_path(bundle_root, manifest_name, violations, code="manifest_path")
    manifest: Mapping[str, Any] | None = None
    if manifest_path is None or not manifest_path.is_file():
        violations.append(BundleViolation("manifest_missing", f"missing manifest: {manifest_name}"))
    else:
        try:
            loaded = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError) as exc:
            violations.append(BundleViolation("manifest_json", f"cannot read manifest: {exc}"))
        else:
            if not isinstance(loaded, Mapping):
                violations.append(BundleViolation("manifest_type", "manifest must be a JSON object"))
            else:
                manifest = loaded
                violations.extend(
                    _validate_manifest(
                        manifest,
                        selected,
                        bundle_track=bundle_track,
                        full_submission=full_submission,
                    )
                )
                violations.extend(_validate_referenced_file(bundle_root, manifest, "wrapper", ".py"))
                violations.extend(_validate_referenced_file(bundle_root, manifest, "robot_config", (".yaml", ".yml", ".json")))
                violations.extend(_validate_robot_config(bundle_root, manifest))
                violations.extend(_validate_readme(bundle_root, manifest))

    json_entries, json_violations = _load_result_files(bundle_root, selected, extension=".json", pattern=_RESULT_NAME)
    violations.extend(json_violations)
    video_entries, video_violations = _load_result_files(bundle_root, selected, extension=".mp4", pattern=_VIDEO_NAME)
    violations.extend(video_violations)
    violations.extend(_validate_output_pairing(json_entries, video_entries))
    violations.extend(_validate_coverage(json_entries, manifest, selected, full_submission=full_submission))
    if manifest is not None:
        violations.extend(_validate_inventory(bundle_root, manifest, json_entries, video_entries))
    return tuple(violations)


def _validate_manifest(
    manifest: Mapping[str, Any],
    profile: SubmissionProfile,
    *,
    bundle_track: str | None,
    full_submission: bool,
) -> list[BundleViolation]:
    violations: list[BundleViolation] = []
    base = behavior_compliance.validate_manifest(manifest, submission=False)
    violations.extend(BundleViolation(item.code, item.detail) for item in base)
    required = (
        "schema_version",
        "behavior_tag",
        "behavior_git_sha",
        "omega_git_sha",
        "weaver_git_sha",
        "track",
        "submission_track",
        "submission_profile",
        "wrapper",
        "robot_config",
        "allowed_observation_keys",
        "task_ids",
        "action_dim",
        "eval_mode",
        "instance_indices",
        "resolved_instance_ids",
        "num_rollouts",
        "outputs_unmodified",
        "artifact_inventory",
    )
    violations.extend(
        BundleViolation("manifest_field", f"missing required field {key!r}") for key in required if key not in manifest
    )
    for key in ("behavior_git_sha", "omega_git_sha", "weaver_git_sha"):
        if key in manifest and not behavior_compliance._is_sha(manifest[key]):  # noqa: SLF001
            violations.extend([BundleViolation("revision", f"{key} must be a hexadecimal git SHA")])
    if manifest.get("behavior_git_sha") != BEHAVIOR_V391_GIT_SHA:
        violations.append(
            BundleViolation(
                "behavior_revision",
                f"v3.9.1 must resolve to {BEHAVIOR_V391_GIT_SHA}",
            )
        )
    if manifest.get("track") != "behavior_2026_single_onboard":
        violations.append(BundleViolation("track", "manifest track must be behavior_2026_single_onboard"))
    if manifest.get("submission_track") != bundle_track:
        violations.append(BundleViolation("submission_track", "manifest submission_track must match bundle basename"))
    if manifest.get("submission_profile") != profile.name:
        violations.append(BundleViolation("submission_profile", f"manifest must declare profile {profile.name!r}"))
    selector = manifest.get("selector")
    if not isinstance(selector, Mapping) or selector.get("oracle_used") is not False:
        violations.append(BundleViolation("oracle", "selector.oracle_used must be false"))
    if not isinstance(selector, Mapping) or selector.get("online_inputs_privileged") is not False:
        violations.append(BundleViolation("privileged_online", "selector.online_inputs_privileged must be false"))
    task_ids = manifest.get("task_ids")
    if not isinstance(task_ids, Sequence) or isinstance(task_ids, (str, bytes)):
        violations.append(BundleViolation("task_ids", "task_ids must be a sequence"))
    else:
        task_values = [str(value) for value in task_ids]
        if not task_values or len(set(task_values)) != len(task_values):
            violations.append(BundleViolation("task_ids", "task_ids must be non-empty and unique"))
        if full_submission and len(task_values) != 100:
            violations.append(BundleViolation("task_count", f"full submission requires 100 tasks, got {len(task_values)}"))
    if manifest.get("eval_mode") != "public_test":
        violations.append(BundleViolation("eval_mode", "submission bundle must use public_test"))
    if list(manifest.get("instance_indices", ())) != list(profile.cli_indices or ()):
        violations.append(BundleViolation("instances", f"instance declaration does not match profile {profile.name}"))
    if list(manifest.get("resolved_instance_ids", ())) != list(profile.instance_ids):
        violations.append(BundleViolation("resolved_instances", f"resolved instance IDs do not match {profile.name}"))
    if manifest.get("num_rollouts") != 1:
        violations.append(BundleViolation("rollouts", "challenge submission requires one rollout"))
    if manifest.get("outputs_unmodified") is not True:
        violations.append(BundleViolation("outputs", "outputs_unmodified must be true (inventory consistency only)"))
    action_dim = manifest.get("action_dim")
    if isinstance(action_dim, bool) or not isinstance(action_dim, int) or action_dim <= 0:
        violations.append(BundleViolation("action_dim", "action_dim must be a positive integer"))
    robot_config = manifest.get("robot_config")
    if isinstance(robot_config, Mapping) and robot_config.get("action_dim") != action_dim:
        violations.append(BundleViolation("action_dim", "robot_config.action_dim must match manifest action_dim"))
    return violations


def _validate_referenced_file(
    root: Path, manifest: Mapping[str, Any], field: str, suffixes: str | tuple[str, ...]
) -> list[BundleViolation]:
    violations: list[BundleViolation] = []
    value = manifest.get(field)
    if not isinstance(value, Mapping):
        return [BundleViolation(field, f"{field} must contain path and sha256")]
    path_value, expected_sha = value.get("path"), value.get("sha256")
    if not isinstance(path_value, str) or not path_value or not isinstance(expected_sha, str) or not _SHA256.fullmatch(expected_sha):
        return [BundleViolation(field, f"{field}.path and {field}.sha256 are required")]
    path = _safe_relative_path(root, path_value, violations, code=f"{field}_path")
    if path is None or not path.is_file():
        violations.append(BundleViolation(f"{field}_missing", f"referenced {field} is missing: {path_value}"))
        return violations
    if not path.name.lower().endswith(suffixes):
        violations.append(BundleViolation(f"{field}_suffix", f"{field} has unsupported suffix: {path.name}"))
    actual = _sha256_file(path)
    if actual.lower() != expected_sha.lower():
        violations.append(BundleViolation(f"{field}_hash", f"{field} SHA-256 does not match manifest"))
    return violations


def _validate_robot_config(root: Path, manifest: Mapping[str, Any]) -> list[BundleViolation]:
    violations: list[BundleViolation] = []
    value = manifest.get("robot_config")
    if not isinstance(value, Mapping) or not isinstance(value.get("path"), str):
        return violations
    path = _safe_relative_path(root, value["path"], violations, code="robot_config_path")
    if path is None or not path.is_file():
        return violations
    try:
        parsed = json.loads(path.read_text(encoding="utf-8")) if path.suffix.lower() == ".json" else yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError, yaml.YAMLError) as exc:
        violations.append(BundleViolation("robot_config_parse", f"cannot parse robot config: {exc}"))
        return violations
    if not isinstance(parsed, Mapping):
        return [BundleViolation("robot_config_type", "robot config must contain one mapping")]
    violations.extend(
        BundleViolation("robot_config_field", f"robot config missing {key!r}")
    for key in ("model", "name", "controller_config", "obs_modalities", "proprio_obs", "sensor_config")
        if key not in parsed
    )
    if not isinstance(parsed.get("model"), str) or parsed.get("model") != parsed.get("model", "").lower():
        violations.append(BundleViolation("robot_model", "robot model must be a non-empty lowercase OmniGibson model id"))
    if "type" in parsed:
        violations.append(BundleViolation("robot_model", "robot config must use model, not deprecated type"))
    if not isinstance(parsed.get("name"), str) or not parsed.get("name"):
        violations.append(BundleViolation("robot_name", "robot config name must be non-empty"))
    if not isinstance(parsed.get("controller_config"), Mapping) or not parsed.get("controller_config"):
        violations.append(BundleViolation("robot_controllers", "controller_config must be a non-empty mapping"))
    modalities = parsed.get("obs_modalities", ())
    if not isinstance(modalities, Sequence) or "proprio" not in modalities or not ({"rgb", "depth"} & set(modalities)):
        violations.append(BundleViolation("robot_modalities", "robot config must expose proprio and RGB/depth"))
    eval_config = parsed.get("eval")
    cameras = eval_config.get("camera_sensor_names") if isinstance(eval_config, Mapping) else None
    if not isinstance(cameras, Mapping) or not {"head", "left_wrist", "right_wrist"}.issubset(cameras):
        violations.append(BundleViolation("robot_cameras", "eval.camera_sensor_names must include head, left_wrist, right_wrist"))
    return violations


def _validate_readme(root: Path, manifest: Mapping[str, Any]) -> list[BundleViolation]:
    violations: list[BundleViolation] = []
    readme = next((root / name for name in ("README", "README.md", "readme.md") if (root / name).is_file()), None)
    if readme is None:
        return [BundleViolation("readme_missing", "submission bundle must contain README or README.md")]
    text = readme.read_text(encoding="utf-8", errors="replace")
    required = ("omnigibson.eval.eval", "--task-name", "--instance-indices", "--num-rollouts", "--output-dir", "--write-video")
    violations.extend(
        [BundleViolation("readme_command", f"README is missing evaluator token {token!r}") for token in required if token not in text]
    )
    for field in ("wrapper", "robot_config"):
        value = manifest.get(field)
        if isinstance(value, Mapping) and isinstance(value.get("path"), str) and value["path"] not in text:
            violations.append(BundleViolation("readme_reference", f"README does not reference {field} path {value['path']!r}"))
    profile = PROFILES.get(str(manifest.get("submission_profile")))
    if profile is not None and profile.cli_indices is not None:
        normalized = " ".join(text.replace("\\\n", " ").split())
        expected = "--instance-indices " + " ".join(str(value) for value in profile.cli_indices)
        if expected not in normalized:
            violations.append(BundleViolation("readme_instances", f"README command must contain {expected!r}"))
    if "--num-rollouts 1" not in " ".join(text.split()):
        violations.append(BundleViolation("readme_rollouts", "README evaluator command must use --num-rollouts 1"))
    return violations


def _load_result_files(root: Path, profile: SubmissionProfile, *, extension: str, pattern: re.Pattern[str]) -> tuple[dict[tuple[str, int, int], Path], list[BundleViolation]]:
    folder = root / ("json" if extension == ".json" else "videos")
    violations: list[BundleViolation] = []
    entries: dict[tuple[str, int, int], Path] = {}
    if not folder.is_dir():
        return entries, [BundleViolation("output_dir", f"missing output directory: {folder.name}")]
    for path in sorted(folder.iterdir()):
        if not path.is_file():
            continue
        if path.suffix.lower() != extension:
            violations.append(BundleViolation("extra_output", f"unexpected file in {folder.name}/: {path.name}"))
            continue
        match = pattern.fullmatch(path.name)
        if match is None:
            violations.append(BundleViolation("output_name", f"invalid {extension} result filename: {path.name}"))
            continue
        key = (match.group("task"), int(match.group("instance")), int(match.group("rollout")))
        if key in entries:
            violations.append(BundleViolation("duplicate_output", f"duplicate output key {key}"))
        entries[key] = path
        if key[1] not in profile.instance_ids:
            violations.append(BundleViolation("instance_id", f"{path.name} is outside profile {profile.name}"))
        if key[2] != 0:
            violations.append(BundleViolation("rollout_id", f"{path.name} must use rollout_id 0"))
        if extension == ".json":
            violations.extend(_validate_metric_json(path, key))
        else:
            violations.extend(_validate_mp4(path))
    return entries, violations


def _validate_metric_json(path: Path, key: tuple[str, int, int]) -> list[BundleViolation]:
    violations: list[BundleViolation] = []
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        return [BundleViolation("metric_json", f"cannot parse {path.name}: {exc}")]
    if not isinstance(value, Mapping):
        return [BundleViolation("metric_json", f"{path.name} must contain an object")]
    expected = {"task": key[0], "instance_id": key[1], "rollout_id": key[2]}
    for field, wanted in expected.items():
        if value.get(field) != wanted:
            violations.append(BundleViolation("metric_identity", f"{path.name} field {field!r} does not match filename"))
    if not isinstance(value.get("success"), bool):
        violations.append(BundleViolation("metric_schema", f"{path.name} success must be boolean"))
    if isinstance(value.get("steps"), bool) or not isinstance(value.get("steps"), int) or value.get("steps", -1) < 0:
        violations.append(BundleViolation("metric_schema", f"{path.name} steps must be a non-negative integer"))
    for path_spec in (
        ("q_score", "final"),
        ("time", "simulator_steps"),
        ("time", "simulator_time"),
        ("time", "normalized_time"),
        ("agent_distance", "base"),
        ("agent_distance", "left"),
        ("agent_distance", "right"),
        ("normalized_agent_distance", "base"),
        ("normalized_agent_distance", "left"),
        ("normalized_agent_distance", "right"),
    ):
        parent, child = path_spec
        item = value.get(parent)
        if not isinstance(item, Mapping) or child not in item or not _finite_number(item[child]):
            violations.append(BundleViolation("metric_schema", f"{path.name} missing finite {parent}.{child}"))
    q_score = value.get("q_score")
    if isinstance(q_score, Mapping) and _finite_number(q_score.get("final")) and not 0.0 <= float(q_score["final"]) <= 1.0:
        violations.append(BundleViolation("metric_range", f"{path.name} q_score.final must be in [0, 1]"))
    return violations


def _validate_mp4(path: Path) -> list[BundleViolation]:
    if path.stat().st_size <= 0:
        return [BundleViolation("video_empty", f"empty rollout video: {path.name}")]
    with path.open("rb") as stream:
        header = stream.read(32)
    if b"ftyp" not in header:
        return [BundleViolation("video_container", f"{path.name} does not have an ISO BMFF/MP4 header")]
    return []


def _validate_output_pairing(json_entries: Mapping[tuple[str, int, int], Path], video_entries: Mapping[tuple[str, int, int], Path]) -> list[BundleViolation]:
    violations: list[BundleViolation] = []
    violations.extend(
        [BundleViolation("missing_video", f"missing MP4 for {key}") for key in sorted(set(json_entries) - set(video_entries))]
    )
    violations.extend(
        [BundleViolation("orphan_video", f"MP4 has no metrics JSON for {key}") for key in sorted(set(video_entries) - set(json_entries))]
    )
    return violations


def _validate_coverage(entries: Mapping[tuple[str, int, int], Path], manifest: Mapping[str, Any] | None, profile: SubmissionProfile, *, full_submission: bool) -> list[BundleViolation]:
    if manifest is None:
        return []
    declared = {str(value) for value in manifest.get("task_ids", ())}
    observed = {key[0] for key in entries}
    violations: list[BundleViolation] = []
    undeclared = observed - declared
    if undeclared:
        violations.append(BundleViolation("task_declaration", f"outputs contain undeclared tasks: {sorted(undeclared)}"))
    if full_submission:
        expected = {(task, instance, 0) for task in declared for instance in profile.instance_ids}
        missing = expected - set(entries)
        extra = set(entries) - expected
        if missing:
            violations.append(BundleViolation("coverage", f"full submission is missing {len(missing)} metric outputs"))
        if extra:
            violations.append(BundleViolation("coverage_extra", f"full submission has {len(extra)} extra metric outputs"))
    return violations


def _validate_inventory(root: Path, manifest: Mapping[str, Any], json_entries: Mapping[tuple[str, int, int], Path], video_entries: Mapping[tuple[str, int, int], Path]) -> list[BundleViolation]:
    inventory = manifest.get("artifact_inventory")
    if not isinstance(inventory, Mapping):
        return [BundleViolation("inventory", "artifact_inventory must map relative paths to size/sha256 records")]
    actual_paths = {path.relative_to(root).as_posix() for path in (*json_entries.values(), *video_entries.values())}
    declared_paths = {str(path) for path in inventory}
    violations: list[BundleViolation] = []
    violations.extend(
        [BundleViolation("inventory_missing", f"artifact is absent from inventory: {path_text}") for path_text in sorted(actual_paths - declared_paths)]
    )
    violations.extend(
        [BundleViolation("inventory_extra", f"inventory references missing/non-output artifact: {path_text}") for path_text in sorted(declared_paths - actual_paths)]
    )
    for path_text in sorted(actual_paths & declared_paths):
        record = inventory[path_text]
        path = root / Path(path_text)
        if not isinstance(record, Mapping) or not isinstance(record.get("sha256"), str) or not _SHA256.fullmatch(record["sha256"]):
            violations.append(BundleViolation("inventory_record", f"invalid inventory record for {path_text}"))
            continue
        if record["sha256"].lower() != _sha256_file(path).lower():
            violations.append(BundleViolation("inventory_hash", f"artifact hash mismatch: {path_text}"))
        if record.get("size") != path.stat().st_size:
            violations.append(BundleViolation("inventory_size", f"artifact size mismatch: {path_text}"))
        if path.stat().st_size <= 0:
            violations.append(BundleViolation("inventory_size", f"artifact is empty: {path_text}"))
    return violations


def _safe_relative_path(root: Path, value: str, violations: list[BundleViolation], *, code: str) -> Path | None:
    path = Path(value)
    if path.is_absolute():
        violations.append(BundleViolation(code, f"path must be relative to bundle: {value!r}"))
        return None
    try:
        resolved = (root / path).resolve()
        resolved.relative_to(root)
    except (OSError, ValueError):
        violations.append(BundleViolation(code, f"path escapes bundle: {value!r}"))
        return None
    return resolved


def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        while chunk := stream.read(1024 * 1024):
            digest.update(chunk)
    return digest.hexdigest()


def _finite_number(value: Any) -> bool:
    return isinstance(value, (int, float, np.number)) and not isinstance(value, bool) and bool(np.isfinite(value))
